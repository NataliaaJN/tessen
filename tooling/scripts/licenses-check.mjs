// licenses:check — condition C10 of ADR 0004: third-party notices and a license allow-list.
//
// Walks the PRODUCTION dependency tree (dependencies + peer ranges are not installed code, so only
// `dependencies`) of every publishable package, reads each installed package's `license`, and:
//   - fails when a license is not in ALLOWED_LICENSES (a new license needs a conscious decision);
//   - fails when THIRD-PARTY-NOTICES.md is out of date (`--write` regenerates it).
//
// Needs `pnpm install` first. No network.

import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const NOTICES = join(root, 'THIRD-PARTY-NOTICES.md');

/** Permissive licenses only. Anything else (GPL, AGPL, SSPL, unknown...) blocks until decided. */
export const ALLOWED_LICENSES = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
]);

/** Packages that are ours, not third-party. */
/** @param {string} name */
const isOwn = (name) => name.startsWith('@tessen-ui/');

/**
 * @param {unknown} license a package.json `license` field
 * @returns {string} an SPDX-ish string, or 'UNKNOWN'
 */
export function normalizeLicense(license) {
  if (typeof license === 'string' && license.trim()) return license.trim();
  const legacy = /** @type {{ type?: unknown } | null | undefined} */ (license);
  if (legacy && typeof legacy === 'object' && typeof legacy.type === 'string') return legacy.type;
  return 'UNKNOWN';
}

/**
 * `(MIT OR Apache-2.0)` is fine when at least one alternative is allowed; `AND` needs all.
 * @param {string} license
 * @param {Set<string>} [allowed]
 */
export function isAllowed(license, allowed = ALLOWED_LICENSES) {
  const expr = license.replace(/[()]/g, ' ').trim();
  if (/\sAND\s/.test(expr)) return expr.split(/\sAND\s/).every((l) => allowed.has(l.trim()));
  return expr.split(/\sOR\s/).some((l) => allowed.has(l.trim()));
}

/** @param {string} path */
function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Resolves an installed dependency the way node does (pnpm keeps them as symlinks). */
/**
 * @param {string} name
 * @param {string} fromDir
 * @returns {string | null}
 */
function findInstalled(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(candidate)) return realpathSync(dirname(candidate));
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/** @returns {Map<string, { name: string, version: string, license: string, repository: string }>} */
export function collectThirdParty() {
  const found = new Map();
  const seen = new Set();
  /**
   * @param {string} name
   * @param {string} fromDir
   * @returns {void}
   */
  const visit = (name, fromDir) => {
    const dir = findInstalled(name, fromDir);
    if (!dir) throw new Error(`${name} is not installed (from ${fromDir}); run pnpm install`);
    if (seen.has(dir)) return;
    seen.add(dir);
    const pkg = readJson(join(dir, 'package.json'));
    if (!isOwn(pkg.name)) {
      const repo =
        typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository?.url ?? '');
      found.set(`${pkg.name}@${pkg.version}`, {
        name: pkg.name,
        version: pkg.version,
        license: normalizeLicense(pkg.license),
        repository: repo.replace(/^git\+/, '').replace(/\.git$/, ''),
      });
    }
    for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir);
  };
  for (const entry of readdirSync(join(root, 'packages'), { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const pkgDir = join(root, 'packages', entry.name);
    const manifest = join(pkgDir, 'package.json');
    if (!existsSync(manifest)) continue;
    for (const dep of Object.keys(readJson(manifest).dependencies ?? {})) visit(dep, pkgDir);
  }
  return found;
}

/** @param {ReturnType<typeof collectThirdParty>} found */
export function renderNotices(found) {
  const rows = [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    '# Third-party notices',
    '',
    'TESSEN packages bundle or depend on the open-source software below. Each keeps its own license.',
    'This file is generated by `pnpm licenses:check -- --write`; do not edit it by hand.',
    '',
    '| Package | Version | License | Source |',
    '| --- | --- | --- | --- |',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repository || '-'} |`),
    '',
  ];
  return lines.join('\n');
}

function main() {
  const found = collectThirdParty();
  const bad = [...found.values()].filter((p) => !isAllowed(p.license));
  if (bad.length > 0) {
    console.error('licenses:check FAILED: licenses outside the allow-list');
    for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`);
    console.error(`Allowed: ${[...ALLOWED_LICENSES].join(', ')}`);
    process.exit(1);
  }
  const expected = renderNotices(found);
  if (process.argv.includes('--write')) {
    writeFileSync(NOTICES, expected);
    console.log(`licenses:check: wrote THIRD-PARTY-NOTICES.md (${found.size} packages).`);
    return;
  }
  const current = existsSync(NOTICES) ? readFileSync(NOTICES, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== expected) {
    console.error(
      'licenses:check FAILED: THIRD-PARTY-NOTICES.md is out of date. Run: pnpm licenses:check --write',
    );
    process.exit(1);
  }
  console.log(
    `licenses:check OK: ${found.size} third-party packages, all allowed; notices up to date.`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
