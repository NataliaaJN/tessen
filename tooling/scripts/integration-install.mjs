// @ts-check
/**
 * `pnpm integration:install` - installs the packed tarballs into every `integration/*`
 * project from a clean state (ADR 0016).
 *
 * For each project it (re)generates `pnpm-workspace.yaml` with `overrides` pointing every
 * internal package at its tarball, so no internal dependency can come from the registry,
 * and makes the project its own pnpm root (it is not part of the repository workspace).
 * Then it removes `node_modules`/lockfile and runs `pnpm install --force`, and finally
 * checks the generated lockfile with the scope rules.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPacked, root } from './pack-all.mjs';
import { checkIntegrationLockfile } from './scope-check.mjs';

/** @returns {string[]} absolute project dirs (`INTEGRATION_ONLY=next` limits it to one project) */
export function integrationProjects() {
  const base = join(root, 'integration');
  if (!existsSync(base)) return [];
  return readdirSync(base)
    .map((d) => join(base, d))
    .filter((d) => statSync(d).isDirectory() && existsSync(join(d, 'package.json')))
    .filter((d) => !process.env['INTEGRATION_ONLY'] || d.endsWith(process.env['INTEGRATION_ONLY']));
}

/**
 * @param {string} dir
 * @param {import('./pack-all.mjs').PackedPackage[]} packed
 */
function workspaceFile(dir, packed) {
  const lines = [
    '# Generated by tooling/scripts/integration-install.mjs - do not edit, not committed.',
    '# Makes this folder its own pnpm root (outside the repository workspace) and forces every',
    '# internal package to the packed tarball (ADR 0016).',
    'overrides:',
    ...packed.map((p) => {
      const rel = relative(dir, join(root, '.tarballs', p.file)).replaceAll('\\', '/');
      return `  '${p.name}': file:${rel}`;
    }),
    '',
    'allowBuilds:',
    '  esbuild: false',
    '',
  ];
  return lines.join('\n');
}

function main() {
  const packed = readPacked();
  const projects = integrationProjects();
  if (projects.length === 0) throw new Error('no integration/* projects found');

  /** @type {string[]} */
  const errors = [];
  for (const dir of projects) {
    const name = relative(root, dir).replaceAll('\\', '/');
    console.log(`\n== ${name}: clean install from tarballs`);
    for (const path of ['node_modules', 'pnpm-lock.yaml', 'dist']) {
      rmSync(join(dir, path), { recursive: true, force: true });
    }
    writeFileSync(join(dir, 'pnpm-workspace.yaml'), workspaceFile(dir, packed));
    const result = spawnSync('pnpm', ['install', '--force'], {
      cwd: dir,
      stdio: 'inherit',
      shell: process.platform === 'win32',
    });
    if (result.status !== 0) {
      errors.push(`${name}: pnpm install failed`);
      continue;
    }
    for (const e of checkIntegrationLockfile(join(dir, 'pnpm-lock.yaml')))
      errors.push(`${name}: ${e}`);
  }
  if (errors.length > 0) {
    console.error(`\nintegration:install failed (${errors.length}):`);
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }
  console.log('\nintegration:install passed');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
